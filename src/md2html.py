@dataclass(frozen=True)
class LocaleConfig:
    """Static labels and paths for one site language."""

    code: str
    html_lang: str
    md_dir: Path
    output_subdir: str
    skip_label: str
    open_nav_label: str
    close_nav_label: str
    site_nav_label: str
    primary_nav_label: str
    footer_label: str
    language_label: str
    language_aria_label: str
    alternate_lang: str

    @property
    def asset_prefix(self) -> str:
        return "../" if self.output_subdir else ""


