@dataclass
class Page:
    """A converted Markdown page ready to be rendered in the site template."""

    slug: str
    source: Path
    body: str
    heading: str
    locale: str
    is_fallback: bool = False


class AcademicLayoutTreeprocessor(Treeprocessor):
    """Add presentational hooks without requiring HTML in the Markdown files."""

    DATE_LABEL = re.compile(
        r"^\d{4}-\d{2}(?:\s*(?:--|–|—)\s*\d{4}-\d{2})?$"
    )

    def __init__(self, md, page_slug: str):
        super().__init__(md)
        self.page_slug = page_slug

    def run(self, root):
        first_profile_image_found = False

        for element in root.iter():
            if element.tag == "img":
                element.set("decoding", "async")
                element.set("loading", "lazy")

        for child in list(root):
            if self.page_slug == "index" and child.tag == "p":
                images = list(child.findall("img"))
                text_is_empty = not (child.text or "").strip()
                if images and text_is_empty and not first_profile_image_found:
                    child.set("class", "profile-photo")
                    images[0].set("loading", "eager")
                    first_profile_image_found = True

                if len(child) > 0 and child[0].tag == "strong":
                    label = "".join(child[0].itertext()).strip()
                    if self.DATE_LABEL.fullmatch(label):
                        child.set("class", "news-item")

            if self.page_slug == "publications" and child.tag == "ul":
                child.set("class", "publication-list")
                for item in child.findall("li"):
                    item.set("class", "publication-item")

        return root


class AcademicLayoutExtension(Extension):
    """Register the academic-layout treeprocessor for one page."""

    def __init__(self, page_slug: str):
        super().__init__()
        self.page_slug = page_slug

    def extendMarkdown(self, md):
        md.treeprocessors.register(
            AcademicLayoutTreeprocessor(md, self.page_slug),
            "academic_layout",
            8,
        )


def preprocess_math_formulas(md_content: str) -> str:
    """Convert TeX delimiters for MathJax while leaving code untouched."""

    protected: Dict[str, str] = {}

    def stash(match) -> str:
        token = f"MD2HTMLPROTECTED{len(protected):04d}TOKEN"
        protected[token] = match.group(0)
        return token

    fenced_code = re.compile(
        r"^[ \t]*(?P<fence>`{3,}|~{3,})[^\n]*\n.*?^[ \t]*(?P=fence)[ \t]*(?:\n|$)",
        flags=re.MULTILINE | re.DOTALL,
    )
    inline_code = re.compile(r"(?P<ticks>`+).*?(?P=ticks)", flags=re.DOTALL)

    prepared = fenced_code.sub(stash, md_content)
    prepared = inline_code.sub(stash, prepared)

    prepared = re.sub(
        r"(?<!\\)\$\$(.+?)(?<!\\)\$\$",
        lambda match: r"\\[" + match.group(1) + r"\\]",
        prepared,
        flags=re.DOTALL,
    )
    prepared = re.sub(
        r"(?<![\\$])\$(?![$\s])([^\n]*?)(?<![\s\\$])\$(?!\$)",
        lambda match: r"\\(" + match.group(1) + r"\\)",
        prepared,
    )

    for token, original in protected.items():
        prepared = prepared.replace(token, original)

    return prepared


def render_markdown(md_content: str, page_slug: str) -> str:
    """Convert one Markdown document to semantic HTML."""

    prepared = preprocess_math_formulas(md_content)
    return markdown.markdown(
        prepared,
        extensions=[
            "extra",
            "sane_lists",
            "toc",
            AcademicLayoutExtension(page_slug),
        ],
        extension_configs={
            "toc": {
                "permalink": False,
            }
        },
        output_format="html5",
    )


def adjust_static_asset_paths(html_content: str, asset_prefix: str) -> str:
    """Adjust repository asset links for pages rendered in a subdirectory."""

    if not asset_prefix:
        return html_content

    asset_pattern = re.compile(r'(?P<attribute>\b(?:src|href))="(?:\./)?src/')
    return asset_pattern.sub(
        lambda match: f'{match.group("attribute")}="{asset_prefix}src/',
        html_content,
    )


def extract_first_heading(html_content: str, fallback: str) -> str:
    """Use the first H1 as the browser title, with a filename fallback."""

    match = re.search(r"<h1(?:\s[^>]*)?>(.*?)</h1>", html_content, re.DOTALL)
    if not match:
        return fallback

    without_tags = re.sub(r"<[^>]+>", "", match.group(1))
    return html.unescape(without_tags).strip() or fallback


def filename_display_name(slug: str) -> str:
    """Turn an English Markdown filename into a readable label."""

    if slug == "index":
        return "Home"
    return slug.replace("_", " ").replace("-", " ").title()


def navigation_label(page: Page, locale: LocaleConfig) -> str:
    """Return a concise navigation label for the requested locale."""

    if locale.code == "en":
        return filename_display_name(page.slug)
    if page.slug == "index":
        return "主页"
    if page.slug == "publications":
        return "研究成果"
    if not page.is_fallback:
        return page.heading
    return filename_display_name(page.slug)


def page_class(slug: str) -> str:
    """Return a safe CSS class derived from a Markdown filename."""

    normalized = re.sub(r"[^a-z0-9_-]+", "-", slug.lower()).strip("-")
    return normalized or "content"


def generate_menu_items(
    pages: List[Page], current_slug: str, locale: LocaleConfig
) -> str:
    """Generate navigation with a current-page state."""

    items = []
    for page in pages:
        active = page.slug == current_slug
        attributes = ' class="active" aria-current="page"' if active else ""
        label = html.escape(navigation_label(page, locale))
        href = html.escape(f"{page.slug}.html", quote=True)
        items.append(f'<li><a href="{href}"{attributes}>{label}</a></li>')
    return "\n                        ".join(items)


def discover_english_files() -> List[Path]:
    """Return the authoritative, stable page list from ``src/md``."""

    if not MD_DIR.is_dir():
        raise RuntimeError(f"Markdown directory not found: {MD_DIR}")

    md_files = sorted(
        MD_DIR.glob("*.md"),
        key=lambda path: (path.stem != "index", path.stem.casefold()),
    )
    if not md_files:
        raise RuntimeError(f"No Markdown files found in {MD_DIR}")
    return md_files


def load_pages(locale: LocaleConfig, english_files: List[Path]) -> List[Page]:
    """Read one locale, using English content when a translation is absent."""

    pages = []
    english_names = {path.name for path in english_files}

    if locale.code == "zh" and locale.md_dir.is_dir():
        for translated_file in sorted(locale.md_dir.glob("*.md")):
            if translated_file.name not in english_names:
                print(
                    "Warning: ignoring Chinese page without an English counterpart: "
                    f"{translated_file.relative_to(PROJECT_ROOT)}"
                )

    for english_file in english_files:
        source = english_file
        is_fallback = False
        if locale.code == "zh":
            translated_file = locale.md_dir / english_file.name
            if translated_file.is_file():
                source = translated_file
            else:
                is_fallback = True
                print(
                    "Warning: Chinese translation missing for "
                    f"{english_file.name}; using English content."
                )

        md_content = source.read_text(encoding="utf-8")
        body = render_markdown(md_content, english_file.stem)
        body = adjust_static_asset_paths(body, locale.asset_prefix)
        fallback_heading = filename_display_name(english_file.stem)
        pages.append(
            Page(
                slug=english_file.stem,
                source=source,
                body=body,
                heading=extract_first_heading(body, fallback_heading),
                locale=locale.code,
                is_fallback=is_fallback,
            )
        )
    return pages


def render_pages(pages: List[Page], locale: LocaleConfig) -> Dict[str, str]:
    """Render one locale inside the shared site template."""

    homepage = next((page for page in pages if page.slug == "index"), pages[0])
    site_title = homepage.heading
    update_time = datetime.now().astimezone().strftime("%Y-%m")
    rendered = {}

    for page in pages:
        document_title = (
            site_title if page.slug == "index" else f"{page.heading} | {site_title}"
        )
        language_href = (
            f"zh/{page.slug}.html"
            if locale.code == "en"
            else f"../{page.slug}.html"
        )
        rendered[f"{page.slug}.html"] = HTML_TEMPLATE.substitute(
            document_title=html.escape(document_title),
            page_class=html.escape(page_class(page.slug), quote=True),
            locale_code=html.escape(locale.code, quote=True),
            html_lang=html.escape(locale.html_lang, quote=True),
            asset_prefix=html.escape(locale.asset_prefix, quote=True),
            skip_label=html.escape(locale.skip_label),
            open_nav_label=html.escape(locale.open_nav_label, quote=True),
            close_nav_label=html.escape(locale.close_nav_label, quote=True),
            site_nav_label=html.escape(locale.site_nav_label, quote=True),
            primary_nav_label=html.escape(locale.primary_nav_label, quote=True),
            site_title=html.escape(site_title),
            menu_items=generate_menu_items(pages, page.slug, locale),
            language_href=html.escape(language_href, quote=True),
            alternate_lang=html.escape(locale.alternate_lang, quote=True),
            language_label=html.escape(locale.language_label),
            language_aria_label=html.escape(
                locale.language_aria_label, quote=True
            ),
            content=page.body,
            footer_label=html.escape(locale.footer_label),
            update_time=html.escape(update_time),
        )

    return rendered


def write_text_atomic(path: Path, content: str) -> None:
    """Replace a text file only after its complete contents are on disk."""

    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp")
    temporary.write_text(content, encoding="utf-8", newline="\n")
    temporary.replace(path)


def remove_stale_generated_pages(directory: Path, expected: Set[str]) -> None:
    """Remove only obsolete files that this generator previously created."""

    if not directory.is_dir():
        return

    for candidate in directory.glob("*.html"):
        if candidate.name in expected:
            continue
        try:
            header = candidate.read_text(encoding="utf-8")[:512]
        except (OSError, UnicodeDecodeError):
            continue
        if GENERATED_MARKER in header:
            candidate.unlink()


def publish(
    english_pages: Dict[str, str], chinese_pages: Dict[str, str]
) -> None:
    """Synchronize both locales and the shared root stylesheet."""

    output_sets = (
        (english_pages, HTML_DIR, PROJECT_ROOT),
        (chinese_pages, HTML_ZH_DIR, PUBLISH_ZH_DIR),
    )
    for rendered_pages, intermediate_dir, publish_dir in output_sets:
        expected = set(rendered_pages)
        for filename, content in rendered_pages.items():
            write_text_atomic(intermediate_dir / filename, content)
            write_text_atomic(publish_dir / filename, content)

        remove_stale_generated_pages(intermediate_dir, expected)
        remove_stale_generated_pages(publish_dir, expected)

    if not STYLE_SOURCE.is_file():
        raise RuntimeError(f"Stylesheet not found: {STYLE_SOURCE}")
    write_text_atomic(STYLE_TARGET, STYLE_SOURCE.read_text(encoding="utf-8"))


def process_md_files() -> None:
    """Build both locales, failing before writes on conversion errors."""

    english_files = discover_english_files()
    english_pages = load_pages(ENGLISH, english_files)
    chinese_pages = load_pages(CHINESE, english_files)
    rendered_english = render_pages(english_pages, ENGLISH)
    rendered_chinese = render_pages(chinese_pages, CHINESE)
    publish(rendered_english, rendered_chinese)

    for page in english_pages:
        print(
            f"Converted {page.source.relative_to(PROJECT_ROOT)} -> "
            f"{page.slug}.html"
        )
    for page in chinese_pages:
        fallback_note = " (English fallback)" if page.is_fallback else ""
        print(
            f"Converted {page.source.relative_to(PROJECT_ROOT)} -> "
            f"zh/{page.slug}.html{fallback_note}"
        )


if __name__ == "__main__":
    process_md_files()
