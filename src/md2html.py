"""Build the bilingual static site from Markdown sources.

English Markdown in ``src/md`` defines the page list. Matching translations in
``src/md_zh`` populate the Chinese site; a missing translation safely falls
back to the English source. Running this script refreshes the checked-in
intermediate HTML and the files served by GitHub Pages.
"""

from dataclasses import dataclass
from datetime import datetime
import html
from pathlib import Path
import re
from string import Template
from typing import Dict, List, Set

import markdown
from markdown.extensions import Extension
from markdown.treeprocessors import Treeprocessor


