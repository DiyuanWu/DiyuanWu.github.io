"""Build the static site from Markdown sources.

The Markdown files in ``src/md`` are the only content source. Running this
script refreshes both the checked-in intermediate HTML in ``src/html`` and the
HTML/CSS files served by GitHub Pages from the repository root.
"""

from dataclasses import dataclass
from datetime import datetime
import html
from pathlib import Path
import re
from string import Template
from typing import Dict, List, Set

import markdown
from markdown.extensions import Extension
from markdown.treeprocessors import Treeprocessor


SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent
MD_DIR = SCRIPT_DIR / "md"
HTML_DIR = SCRIPT_DIR / "html"
STYLE_SOURCE = SCRIPT_DIR / "css" / "styles.css"
STYLE_TARGET = PROJECT_ROOT / "styles.css"
GENERATED_MARKER = "Generated by src/md2html.py"


HTML_TEMPLATE = Template(
    r"""<!DOCTYPE html>
<!-- Generated by src/md2html.py. Edit src/md/*.md instead. -->
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <meta name="theme-color" content="#ffffff">
    <title>${document_title}</title>
    <link rel="stylesheet" href="styles.css">
    <script>
        window.MathJax = {
            tex: {
                inlineMath: [['\\(', '\\)']],
                displayMath: [['\\[', '\\]']],
                processEscapes: true
            },
            options: {
                skipHtmlTags: ['script', 'noscript', 'style', 'textarea', 'pre', 'code']
            }
        };
    </script>
    <script id="MathJax-script" defer src="https://cdn.jsdelivr.net/npm/mathjax@3/es5/tex-mml-chtml.js"></script>
</head>
<body class="page-${page_class}">
    <a class="skip-link" href="#main-content">Skip to content</a>
    <div id="layout-wrapper">
        <button id="menu-toggle" type="button" aria-label="Open navigation" aria-controls="layout-menu" aria-expanded="false">
            <span class="menu-icon" aria-hidden="true"></span>
        </button>
        <div id="menu-backdrop" aria-hidden="true"></div>

        <aside id="layout-menu" aria-label="Site navigation">
            <div class="sidebar-inner">
                <a class="site-name" href="index.html">${site_title}</a>
                <nav aria-label="Primary navigation">
                    <ul>
                        ${menu_items}
                    </ul>
                </nav>
            </div>
        </aside>

        <main id="layout-content">
            <article id="main-content" class="markdown-body">
                ${content}
            </article>
            <footer id="footer">
                Last updated: ${update_time}
            </footer>
        </main>
    </div>
    <script src="src/js/menu-toggle.js" defer></script>
</body>
</html>
"""
)


@dataclass
class Page:
    """A converted Markdown page ready to be rendered in the site template."""

    slug: str
    source: Path
    body: str
    heading: str


class AcademicLayoutTreeprocessor(Treeprocessor):
    """Add presentational hooks without requiring HTML in the Markdown files."""

    DATE_LABEL = re.compile(
        r"^\d{4}-\d{2}(?:\s*(?:--|–|—)\s*\d{4}-\d{2})?$"
    )

    def __init__(self, md, page_slug: str):
        super().__init__(md)
        self.page_slug = page_slug

    def run(self, root):
        first_profile_image_found = False

        for element in root.iter():
            if element.tag == "img":
                element.set("decoding", "async")
                element.set("loading", "lazy")

        for child in list(root):
            if self.page_slug == "index" and child.tag == "p":
                images = list(child.findall("img"))
                text_is_empty = not (child.text or "").strip()
                if images and text_is_empty and not first_profile_image_found:
                    child.set("class", "profile-photo")
                    images[0].set("loading", "eager")
                    first_profile_image_found = True

                if len(child) > 0 and child[0].tag == "strong":
                    label = "".join(child[0].itertext()).strip()
                    if self.DATE_LABEL.fullmatch(label):
                        child.set("class", "news-item")

            if self.page_slug == "publications" and child.tag == "ul":
                child.set("class", "publication-list")
                for item in child.findall("li"):
                    item.set("class", "publication-item")

        return root


class AcademicLayoutExtension(Extension):
    """Register the academic-layout treeprocessor for one page."""

    def __init__(self, page_slug: str):
        super().__init__()
        self.page_slug = page_slug

    def extendMarkdown(self, md):
        md.treeprocessors.register(
            AcademicLayoutTreeprocessor(md, self.page_slug),
            "academic_layout",
            8,
        )


def preprocess_math_formulas(md_content: str) -> str:
    """Convert TeX delimiters for MathJax while leaving code untouched."""

    protected: Dict[str, str] = {}

    def stash(match) -> str:
        token = f"MD2HTMLPROTECTED{len(protected):04d}TOKEN"
        protected[token] = match.group(0)
        return token

    fenced_code = re.compile(
        r"^[ \t]*(?P<fence>`{3,}|~{3,})[^\n]*\n.*?^[ \t]*(?P=fence)[ \t]*(?:\n|$)",
        flags=re.MULTILINE | re.DOTALL,
    )
    inline_code = re.compile(r"(?P<ticks>`+).*?(?P=ticks)", flags=re.DOTALL)

    prepared = fenced_code.sub(stash, md_content)
    prepared = inline_code.sub(stash, prepared)

    prepared = re.sub(
        r"(?<!\\)\$\$(.+?)(?<!\\)\$\$",
        lambda match: r"\\[" + match.group(1) + r"\\]",
        prepared,
        flags=re.DOTALL,
    )
    prepared = re.sub(
        r"(?<![\\$])\$(?![$\s])([^\n]*?)(?<![\s\\$])\$(?!\$)",
        lambda match: r"\\(" + match.group(1) + r"\\)",
        prepared,
    )

    for token, original in protected.items():
        prepared = prepared.replace(token, original)

    return prepared


def render_markdown(md_content: str, page_slug: str) -> str:
    """Convert one Markdown document to semantic HTML."""

    prepared = preprocess_math_formulas(md_content)
    return markdown.markdown(
        prepared,
        extensions=[
            "extra",
            "sane_lists",
            "toc",
            AcademicLayoutExtension(page_slug),
        ],
        extension_configs={
            "toc": {
                "permalink": False,
            }
        },
        output_format="html5",
    )


def extract_first_heading(html_content: str, fallback: str) -> str:
    """Use the first H1 as the browser title, with a filename fallback."""

    match = re.search(r"<h1(?:\s[^>]*)?>(.*?)</h1>", html_content, re.DOTALL)
    if not match:
        return fallback

    without_tags = re.sub(r"<[^>]+>", "", match.group(1))
    return html.unescape(without_tags).strip() or fallback


def display_name(slug: str) -> str:
    """Turn a Markdown filename into a readable navigation label."""

    if slug == "index":
        return "Home"
    return slug.replace("_", " ").replace("-", " ").title()


def page_class(slug: str) -> str:
    """Return a safe CSS class derived from a Markdown filename."""

    normalized = re.sub(r"[^a-z0-9_-]+", "-", slug.lower()).strip("-")
    return normalized or "content"


def generate_menu_items(pages: List[Page], current_slug: str) -> str:
    """Generate navigation with a current-page state."""

    items = []
    for page in pages:
        active = page.slug == current_slug
        attributes = ' class="active" aria-current="page"' if active else ""
        label = html.escape(display_name(page.slug))
        href = html.escape(f"{page.slug}.html", quote=True)
        items.append(f'<li><a href="{href}"{attributes}>{label}</a></li>')
    return "\n                        ".join(items)


def load_pages() -> List[Page]:
    """Read and convert every Markdown file before writing any output."""

    if not MD_DIR.is_dir():
        raise RuntimeError(f"Markdown directory not found: {MD_DIR}")

    md_files = sorted(
        MD_DIR.glob("*.md"),
        key=lambda path: (path.stem != "index", path.stem.casefold()),
    )
    if not md_files:
        raise RuntimeError(f"No Markdown files found in {MD_DIR}")

    pages = []
    for md_file in md_files:
        md_content = md_file.read_text(encoding="utf-8")
        body = render_markdown(md_content, md_file.stem)
        fallback = display_name(md_file.stem)
        pages.append(
            Page(
                slug=md_file.stem,
                source=md_file,
                body=body,
                heading=extract_first_heading(body, fallback),
            )
        )
    return pages


def render_pages(pages: List[Page]) -> Dict[str, str]:
    """Render all converted pages inside the shared site template."""

    homepage = next((page for page in pages if page.slug == "index"), pages[0])
    site_title = homepage.heading
    update_time = datetime.now().astimezone().strftime("%Y-%m")
    rendered = {}

    for page in pages:
        document_title = (
            site_title if page.slug == "index" else f"{page.heading} | {site_title}"
        )
        rendered[f"{page.slug}.html"] = HTML_TEMPLATE.substitute(
            document_title=html.escape(document_title),
            page_class=html.escape(page_class(page.slug), quote=True),
            site_title=html.escape(site_title),
            menu_items=generate_menu_items(pages, page.slug),
            content=page.body,
            update_time=html.escape(update_time),
        )

    return rendered


def write_text_atomic(path: Path, content: str) -> None:
    """Replace a text file only after its complete contents are on disk."""

    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp")
    temporary.write_text(content, encoding="utf-8", newline="\n")
    temporary.replace(path)


def remove_stale_generated_pages(directory: Path, expected: Set[str]) -> None:
    """Remove only obsolete files that this generator previously created."""

    if not directory.is_dir():
        return

    for candidate in directory.glob("*.html"):
        if candidate.name in expected:
            continue
        try:
            header = candidate.read_text(encoding="utf-8")[:512]
        except (OSError, UnicodeDecodeError):
            continue
        if GENERATED_MARKER in header:
            candidate.unlink()


def publish(rendered_pages: Dict[str, str]) -> None:
    """Synchronize generated HTML and the root stylesheet."""

    expected = set(rendered_pages)
    for filename, content in rendered_pages.items():
        write_text_atomic(HTML_DIR / filename, content)
        write_text_atomic(PROJECT_ROOT / filename, content)

    remove_stale_generated_pages(HTML_DIR, expected)
    remove_stale_generated_pages(PROJECT_ROOT, expected)

    if not STYLE_SOURCE.is_file():
        raise RuntimeError(f"Stylesheet not found: {STYLE_SOURCE}")
    write_text_atomic(STYLE_TARGET, STYLE_SOURCE.read_text(encoding="utf-8"))


def process_md_files() -> None:
    """Build and publish all pages, failing before writes on conversion errors."""

    pages = load_pages()
    rendered_pages = render_pages(pages)
    publish(rendered_pages)

    for page in pages:
        print(f"Converted {page.source.relative_to(PROJECT_ROOT)} -> {page.slug}.html")


if __name__ == "__main__":
    process_md_files()
